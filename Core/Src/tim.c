/**
  * @brief TIM 中断回调函数
	* @param TIM_HandleTypeDef *htim 定时器句柄
  * @retval None
  */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim){
// TIM2：1kHz中断，读 IMU + Kalman 融合
	if (htim->Instance == TIM2){
		MPU6050_Read_All(&hi2c1, &MyMPU6050);

		float acc_roll  = Kalman_GetRoll (MyMPU6050.Ax, MyMPU6050.Ay, MyMPU6050.Az);
		float acc_pitch = Kalman_GetPitch(MyMPU6050.Ax, MyMPU6050.Ay, MyMPU6050.Az);

		roll  = Kalman_Update(&kf_roll,  acc_roll,  MyMPU6050.Gx, 0.001f);
		pitch = Kalman_Update(&kf_pitch, acc_pitch, MyMPU6050.Gy, 0.001f);
	}
// TIM3: 100Hz中断，串口 DMA 发送角度数据
	else if (htim->Instance == TIM3){
		if (tx_ready){
			tx_ready = 0;// 置0表示繁忙
			
			static struct {
					float roll;
					float pitch;
					uint32_t tail;
			} frame = { .tail = 0x7F800000 };   // JustFloat 帧尾

			frame.roll = roll;
			frame.pitch = pitch;
			HAL_UART_Transmit_DMA(&huart1, (uint8_t *)&frame, sizeof(frame));
		}	
	}
}
